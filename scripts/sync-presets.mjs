#!/usr/bin/env node
/**
 * Regenerates src/presets.ts from truepeptidesource.com's own calculator
 * presets (https://truepeptidesource.com/calculators/presets/<slug>), using
 * the same rules the site's calculators use to fill a preset:
 *
 * - vial: the first listed vial size
 * - water: the smallest water volume the site's sources tie to that vial
 *   (else the smallest listed volume)
 * - blends: the first listed composition
 * - starting dose: the default protocol's first titration step, else the
 *   low end of its range, with that protocol's origin label
 *
 * Only numbers and labels are copied. Run: node scripts/sync-presets.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SITE = "https://truepeptidesource.com";
const SLUGS = [
  "semaglutide",
  "tirzepatide",
  "retatrutide",
  "bpc-157",
  "tb-500",
  "ipamorelin",
  "cjc-1295",
  "ghk-cu",
  "bpc-157-tb-500-blend",
  "klow",
  "glow",
];

/** Widget-facing aliases, so data-peptide="bpc-157-tb-500" works too. */
const ALIASES = { "bpc-157-tb-500": "bpc-157-tb-500-blend", "bpc-tb": "bpc-157-tb-500-blend" };

function waterFor(preset, vialMg) {
  const tied = preset.waterVolumes.filter((w) => w.vialMg === vialMg);
  const list = (tied.length > 0 ? tied : preset.waterVolumes).map((w) => w.ml);
  return [...new Set(list)].sort((a, b) => a - b);
}

function startingDose(preset) {
  const protocol = preset.protocols[0];
  if (!protocol) return null;
  const step = protocol.steps[0];
  const dose = step ? step.dose : { value: protocol.range.min, unit: protocol.range.unit };
  if (dose.unit !== "mg" && dose.unit !== "mcg") return null;
  return {
    value: dose.value,
    unit: dose.unit,
    // A total_blend protocol doses the whole blend; anything else one peptide.
    appliesTo: protocol.appliesTo.kind === "component" ? protocol.appliesTo.slug : protocol.appliesTo.kind === "total_blend" ? "blend" : "dose",
    origin: protocol.originLabel,
    goal: protocol.goal,
  };
}

async function load(slug) {
  const res = await fetch(`${SITE}/calculators/presets/${slug}`, { headers: { accept: "application/json" } });
  if (!res.ok) throw new Error(`${slug}: HTTP ${res.status}`);
  return res.json();
}

const presets = {};
for (const slug of SLUGS) {
  const p = await load(slug);
  const vial = p.vialSizes.find((s) => s.unit === "mg");
  const composition = p.isBlend ? p.compositions[0] : null;
  const vialMg = composition ? Number(composition.components.reduce((s, c) => s + c.mg, 0).toPrecision(12)) : (vial?.value ?? null);
  const water = vialMg === null ? [] : waterFor(p, vialMg);
  const start = startingDose(p);
  // A component-dosed blend protocol would need a target picker; the widget doses blends as a whole.
  const usableStart = start && (!p.isBlend || start.appliesTo === "blend") ? start : null;
  presets[slug] = {
    slug,
    name: p.name,
    isBlend: p.isBlend,
    vialMg,
    vialSizesMg: p.vialSizes.filter((s) => s.unit === "mg").map((s) => s.value),
    waterMl: water[0] ?? null,
    components: composition ? composition.components.map((c) => ({ name: c.name, mg: c.mg })) : [],
    startingDose: usableStart
      ? { value: usableStart.value, unit: usableStart.unit, origin: usableStart.origin, goal: usableStart.goal }
      : null,
    page: `${SITE}/peptides/${slug}`,
  };
}

const today = new Date().toISOString().slice(0, 10);
const out = `// Generated by scripts/sync-presets.mjs from ${SITE}/calculators/presets/<slug> on ${today}. Do not edit by hand.

/** One peptide in a blend preset. */
export interface PresetComponent {
  readonly name: string;
  readonly mg: number;
}

/**
 * A calculator preset, filled the way truepeptidesource.com fills its own
 * calculators. \`startingDose\` is what the site's default protocol starts at,
 * labelled by where that number comes from: it describes what studies and
 * communities report, not a recommendation.
 */
export interface Preset {
  readonly slug: string;
  readonly name: string;
  readonly isBlend: boolean;
  /** Vial size the calculator starts on (label total for blends). */
  readonly vialMg: number | null;
  /** Vial sizes the site lists, in mg. */
  readonly vialSizesMg: readonly number[];
  readonly waterMl: number | null;
  /** Blend contents; empty for single peptides. */
  readonly components: readonly PresetComponent[];
  readonly startingDose: {
    readonly value: number;
    readonly unit: "mg" | "mcg";
    /** "Clinical study", "FDA / regulator", "Protocol sites" or "Community reported". */
    readonly origin: string;
    readonly goal: string;
  } | null;
  /** The peptide's page, with every dose and its sources. */
  readonly page: string;
}

export const PRESETS_SOURCE = { url: "${SITE}/calculators/presets", synced: "${today}" } as const;

export const PRESETS: Readonly<Record<string, Preset>> = ${JSON.stringify(presets, null, 2)};

/** Alternate data-peptide spellings. */
export const PRESET_ALIASES: Readonly<Record<string, string>> = ${JSON.stringify(ALIASES, null, 2)};
`;

writeFileSync(fileURLToPath(new URL("../src/presets.ts", import.meta.url)), out);
console.log(`Wrote ${SLUGS.length} presets (${today}).`);
